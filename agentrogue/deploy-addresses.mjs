import { keccak256, toHex, getContractAddress, concat, createPublicClient, http, encodeFunctionData, encodeAbiParameters, decodeFunctionResult } from "viem";
import { bsc } from "viem/chains";
import fs from "fs";
const D = "/workspace/work/pkr/contracts/";
const impl = JSON.parse(fs.readFileSync(D + "AgentRogueRecords.json"));
const prox = JSON.parse(fs.readFileSync(D + "ERC1967Proxy.json"));
const OWNER = "0x519495D2C2333c809FB6862060087d6023831Ddf";
const DEPLOYER = "0x4e59b44847b379578588920cA78FbF26c0B4956C";
const saltI = keccak256(toHex("AgentRogueRecords.impl.v1"));
const implAddr = getContractAddress({ opcode: "CREATE2", from: DEPLOYER, salt: saltI, bytecode: impl.bytecode });
const initData = encodeFunctionData({ abi: impl.abi, functionName: "initialize", args: [OWNER] });
const proxyInit = concat([prox.bytecode, encodeAbiParameters([{ type: "address" }, { type: "bytes" }], [implAddr, initData])]);
const saltP = keccak256(toHex("AgentRogueRecords.proxy.v1"));
const proxyAddr = getContractAddress({ opcode: "CREATE2", from: DEPLOYER, salt: saltP, bytecode: proxyInit });
const dataI = concat([saltI, impl.bytecode]);
const dataP = concat([saltP, proxyInit]);
const c = createPublicClient({ chain: bsc, transport: http("https://bsc-dataseed.bnbchain.org") });
const gp = await c.getGasPrice();
const gasI = await c.estimateGas({ account: OWNER, to: DEPLOYER, data: dataI });
const ov = [{ address: implAddr, code: impl.runtime }];
const simP = await c.call({ account: OWNER, to: DEPLOYER, data: dataP, stateOverride: ov });
const gasP = await c.estimateGas({ account: OWNER, to: DEPLOYER, data: dataP, stateOverride: ov });
fs.writeFileSync(D + "deploy.json", JSON.stringify({ DEPLOYER, OWNER, implAddr, proxyAddr, dataI, dataP, gasI: gasI.toString(), gasP: gasP.toString() }, null, 1));
console.log({ implAddr, proxyAddr, simP: simP.data, gasI: gasI.toString(), gasP: gasP.toString(), gwei: Number(gp) / 1e9, totalBNB: Number((gasI + gasP) * gp) / 1e18 });
